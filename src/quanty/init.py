def check_name(name: str) -> str:
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
        raise ValueError(
            f"strategy name {name!r}: use lowercase letters, digits and _ (a Python module name)"
        )
    return name


# files `quanty upgrade` refreshes from newer templates, while they still carry MARK
REFRESHED = (
    "Dockerfile",
    ".dockerignore",
    "compose.yaml",
    "deploy/cloud-init.yaml",
    "deploy/digitalocean.tf",
    "deploy/.gitignore",
    "README.md",
    "AGENTS.md",
)
MARK = "Generated by quanty init; `quanty upgrade` refreshes it. Delete this line to keep your own edits."


def _marked(rel: str, text: str) -> str:
    line = f"<!-- {MARK} -->" if rel.endswith(".md") else f"# {MARK}"
    if text.startswith("#cloud-config\n"):  # must stay the first line
        head, rest = text.split("\n", 1)
        return f"{head}\n{line}\n{rest}"
    return f"{line}\n{text}"


def has_mark(text: str) -> bool:
    return MARK in "\n".join(text.splitlines()[:3])


def files(a: Answers, name: str = "my-quanty") -> dict[str, str]:
    """Project files, relative path -> content. name: the project's (folder) name."""
    out = _files(a, name)
    return {rel: _marked(rel, text) if rel in REFRESHED else text for rel, text in out.items()}


def _files(a: Answers, name: str) -> dict[str, str]:
    first = next((f"{v}:{a.series[v][0]}" for v in a.venues if a.series.get(v)), "kalshi:KXBTC15M")
    return {
        ".env": _env(a),
        ".gitignore": ".env\n.env.*\ndata/\n__pycache__/\n.venv/\n",
        ".dockerignore": ".env\ndata/\n.git/\n__pycache__/\n.venv/\ndeploy/\n",
        "feeds.toml": _feeds(a),
        "experiments/main.toml": _experiment(a),
        f"strategies/{a.strategy}.py": _strategy(a.strategy, first),
        "Dockerfile": DOCKERFILE,
        "compose.yaml": COMPOSE,
        "deploy/cloud-init.yaml": CLOUD_INIT,
        "deploy/digitalocean.tf": DIGITALOCEAN,
        "deploy/.gitignore": "# OpenTofu's; its state says what it made\n.terraform/\n*.tfstate*\n",
        "fly.toml": FLY.format(app=name),
        "README.md": _readme(a, name),
        "AGENTS.md": _agents(a, first),
        "CLAUDE.md": "@AGENTS.md\n",
        ".mcp.json": MCP_JSON,
        ".claude/settings.json": CLAUDE_SETTINGS,
    }


def create(dest: Path, a: Answers, *, force: bool = False, vendor: bool | None = None) -> list[str]:
    """Write the project; returns what was written. Refuses to overwrite without force.
    vendor: build a quanty wheel into vendor/ (None = when running from a source checkout)."""
    check_name(a.strategy)
    out = files(a, _slug(dest))
    clash = [p for p in out if (dest / p).exists()]
    if clash and not force:
        raise ValueError(f"{dest} already has {', '.join(clash)} (use --force to overwrite)")
    for rel, text in out.items():
        path = dest / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    os.chmod(dest / ".env", 0o600)
    (dest / "data").mkdir(exist_ok=True)
    written = list(out)
    checkout = Path(quanty.__file__).resolve().parents[2]
    if vendor is None:
        vendor = (checkout / "pyproject.toml").exists()
    wheels = _vendor(checkout, dest / "vendor") if vendor else []
    (dest / "pyproject.toml").write_text(_pyproject(dest, wheels[0] if wheels else None))
    return [*written, *wheels, "pyproject.toml"]


def git_init(dest: Path) -> str:
    """Make the project a git repository with a first commit (.env and data/ are ignored; the
    vendored wheel is kept, so the project builds anywhere). Returns what it did, for the CLI."""
    if shutil.which("git") is None:
        return "git isn't installed, so this isn't a repository yet"

    def git(*args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(["git", "-C", str(dest), *args], capture_output=True, text=True, timeout=60)

    top = git("rev-parse", "--show-toplevel")
    if top.returncode == 0:
        return f"already inside the git repository at {top.stdout.strip()}; made no new one"
    git("init", "-q", "-b", "main")
    git("add", "-A")
    done = git("commit", "-q", "-m", "quanty init")
    if done.returncode != 0:
        why = (done.stderr.strip().splitlines() or ["?"])[-1]
        return f"made a git repository, but couldn't commit ({why}): commit the files yourself"
    return "made a git repository with a first commit: push it to a private remote to back it up"


def vendored(dest: Path) -> bool:
    """Whether a project installs quanty from a wheel in vendor/ (else from PyPI)."""
    return any((dest / "vendor").glob(WHEELS))


def upgrade(dest: Path, source: Path | None) -> tuple[str, list[str], list[str]]:
    """Bring a project onto a newer quanty, then refresh its generated files (see `refresh`). A
    vendored project needs `source`, a quanty checkout to build the new wheel from (its
    pyproject.toml is pointed at the new wheel, quanty-py); one on PyPI moves to the latest release
    its pyproject.toml allows, and its files are refreshed by that release's own templates.
    Returns (what it's on now, files refreshed, files kept because they're your own now)."""
    if not (dest / "pyproject.toml").exists() or not (dest / "experiments").is_dir():
        raise ValueError(f"{dest.resolve()} isn't a quanty project (no pyproject.toml and experiments/)")
    if not vendored(dest):
        _uv(dest, ["lock", "-q", "--upgrade-package", PACKAGE], ["sync", "-q"])
        done = subprocess.run(["uv", "run", "quanty", "upgrade", "--refresh-only"], cwd=dest,
                              capture_output=True, text=True)  # fmt: skip
        if done.returncode:
            raise ValueError(f"refreshing with the new release: {done.stderr.strip()[-300:]}")
        version = subprocess.run(["uv", "run", "python", "-c", "import quanty; print(quanty.__version__)"],
                                 cwd=dest, capture_output=True, text=True).stdout.strip()  # fmt: skip
        lines = done.stdout.splitlines()
        got = {k: v.split(", ") for k, _, v in (line.partition(": ") for line in lines) if v}
        return f"quanty {version} from PyPI", got.get("refreshed", []), got.get("kept", [])
    if source is None or not (source / "pyproject.toml").exists() or not (source / "src" / "quanty").is_dir():
        raise ValueError(f"{source} isn't a quanty checkout")
    with tempfile.TemporaryDirectory() as tmp:  # built aside: a failed build leaves the old wheel
        built = _vendor(source, Path(tmp))
        if not built:
            raise ValueError(f"couldn't build a wheel from {source} (is uv installed?)")
        vendor = dest / "vendor"
        for old in vendor.glob(WHEELS):
            old.unlink()
        for name in built:
            shutil.move(Path(tmp) / Path(name).name, vendor / Path(name).name)
    (vendor / ".gitignore").unlink(missing_ok=True)
    _point_at(dest, built[0])
    _uv(dest, ["lock", "-q", "--upgrade-package", PACKAGE], ["sync", "-q"])
    commit = subprocess.run(["git", "-C", str(source), "rev-parse", "--short=12", "HEAD"],
                            capture_output=True, text=True).stdout.strip()  # fmt: skip
    refreshed, kept = refresh(dest)
    return f"quanty {quanty.__version__} at {commit or source}", refreshed, kept


def refresh(dest: Path) -> tuple[list[str], list[str]]:
    """Rewrite the generated files that still carry MARK from this quanty's templates; strategies,
    experiments, feeds, keys and anything without MARK are never touched. (refreshed, kept)."""
    a = _answers_of(dest)
    fresh, plain = files(a, _slug(dest)), _files(a, _slug(dest))
    refreshed, kept = [], []
    for rel in REFRESHED:
        path = dest / rel
        current = path.read_text() if path.exists() else None
        # yours once its mark is gone; unmarked but exactly the template (from before marks): ours
        if current is not None and not has_mark(current) and current != plain[rel]:
            kept.append(rel)
        elif current != fresh[rel]:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(fresh[rel])
            refreshed.append(rel)
    return refreshed, kept


def _point_at(dest: Path, wheel: str) -> None:
    """Make pyproject.toml depend on quanty-py from `wheel` (also moving a project from before the
    rename, which depended on "quanty"), keeping its other contents and comments."""
    import tomlkit

    path = dest / "pyproject.toml"
    doc = tomlkit.parse(path.read_text())
    deps = doc["project"]["dependencies"]
    keep = [d for d in deps if re.split(r"[<>=!~ @\[;]", str(d), maxsplit=1)[0] not in ("quanty", PACKAGE)]
    deps.clear()
    for d in [*keep, PACKAGE]:
        deps.append(d)
    uv = doc.setdefault("tool", tomlkit.table()).setdefault("uv", tomlkit.table())
    sources = uv.setdefault("sources", tomlkit.table())
    sources.pop("quanty", None)
    sources[PACKAGE] = tomlkit.inline_table()
    sources[PACKAGE]["path"] = wheel
    path.write_text(tomlkit.dumps(doc))


def _uv(dest: Path, *commands: list[str]) -> None:
    for args in commands:
        done = subprocess.run(["uv", *args], cwd=dest, capture_output=True, text=True)
        if done.returncode:
            raise ValueError(f"uv {' '.join(args)}: {done.stderr.strip()[-300:]}")


def _answers_of(dest: Path) -> Answers:
    """What `quanty init` was told, as far as the project shows it: its first strategy, and the
    venues and series in feeds.toml (the README and AGENTS.md mention them)."""
    import tomllib

    names = sorted(p.stem for p in (dest / "strategies").glob("*.py") if not p.name.startswith("_"))
    feeds = (
        tomllib.loads((dest / "feeds.toml").read_text()).get("feeds", {})
        if (dest / "feeds.toml").exists()
        else {}
    )
    a = Answers(
        strategy=names[0] if names else "my_strategy", venues=[v for v in DEFAULT_SERIES if v in feeds]
    )
    for v in a.venues:
        given = feeds[v].get("series") or []
        a.series[v] = [s["name"] if isinstance(s, dict) else str(s) for s in given] or a.series[v]
    return a


def _vendor(checkout: Path, into: Path) -> list[str]:
    into.mkdir(exist_ok=True)
    for old in into.glob(WHEELS):
        old.unlink()
    try:
        subprocess.run(
            ["uv", "build", "--wheel", "-q", "-o", str(into), str(checkout)],
            check=True,
            capture_output=True,
            timeout=300,
        )
    except (OSError, subprocess.SubprocessError):
        return []
    (into / ".gitignore").unlink(missing_ok=True)  # uv build ignores its output; the wheel is committed
    return [f"vendor/{w.name}" for w in into.glob(WHEELS)]


def _slug(dest: Path) -> str:
    return re.sub(r"[^a-z0-9]+", "-", dest.resolve().name.lower()).strip("-") or "quanty-project"


def _pyproject(dest: Path, wheel: str | None) -> str:
    """A uv project depending on quanty (a vendored wheel, else this release line on PyPI), so
    `uv run quanty` just works."""
    major, minor = (int(x) for x in quanty.__version__.split(".")[:2])
    dep = f'"{PACKAGE}"' if wheel else f'"{PACKAGE}>={quanty.__version__},<{major}.{minor + 1}"'
    sources = f'\n[tool.uv.sources]\n{PACKAGE} = {{ path = "{wheel}" }}\n' if wheel else ""
    return f"""[project]
name = "{_slug(dest)}"
version = "0.1.0"
requires-python = ">=3.12"
dependencies = [{dep}]

[tool.uv]
package = false   # your strategies are loaded from strategies/, not installed
{sources}"""


def _env(a: Answers) -> str:
    lines = [
        "# API keys for the venues this project trades. Never commit this file.",
        "",
        "# Dashboard login (off when unset): `quanty password --write` sets it",
        "# QUANTY_UI_PASSWORD=",
        "",
    ]
    if "kalshi" in a.venues:
        lines += [
            "# Kalshi: key id and PEM private key (Ed25519 or RSA), inline so it travels with .env to a",
            "# server or container (a key file path would point at nothing there)",
            f"KALSHI_KEY_ID={a.kalshi_key_id}",
            f"KALSHI_SECRET_KEY={inline_pem(a.kalshi_key_path) if a.kalshi_key_path else ''}",
            "",
        ]
    if "polymarket_us" in a.venues:
        lines += [
            "# Polymarket US: key id and base64 Ed25519 private key",
            f"POLYMARKET_KEY_ID={a.polymarket_key_id}",
            f"POLYMARKET_SECRET_KEY={a.polymarket_secret}",
            "",
        ]
    return "\n".join(lines)


def inline_pem(path: str) -> str:
    """A PEM key file as one double-quoted .env value, newlines escaped (dotenv, compose and
    `fly secrets import` all read it; quanty also accepts the quotes and escapes left in)."""
    try:
        text = Path(path).expanduser().read_text().strip()
    except OSError as exc:
        raise ValueError(f"Kalshi private key file {path}: {exc.strerror or exc}") from None
    if "-----BEGIN" not in text:
        raise ValueError(f"Kalshi private key file {path}: not a PEM key")
    return '"' + text.replace("\n", "\\n") + '\\n"'


def _feeds(a: Answers) -> str:
    out = [
        "# Venues and series this project connects to. `quanty feeds list` shows every feed kind.",
        "",
        "[recording]",
        "keep_days = 30   # delete recordings older than this (a busy Kalshi feed records GBs a day)",
        "",
    ]
    if "kalshi" in a.venues:
        series = ", ".join(f'"{s}"' for s in a.series.get("kalshi") or DEFAULT_SERIES["kalshi"])
        out += [
            "[feeds.kalshi]",
            f"series = [{series}]   # any Kalshi series ticker, e.g. KXHIGHNY (NYC high)",
            'index_ids = ["BRTI"]   # CF Benchmarks indexes BTC markets settle on',
            "",
        ]
    if "polymarket_us" in a.venues:
        out += ["[feeds.polymarket_us]", "series = ["]
        for name in a.series.get("polymarket_us") or DEFAULT_SERIES["polymarket_us"]:
            prefix, period = PM_SERIES.get(name, (name.replace("_", "-"), 900))
            out.append(f'  {{ name = "{name}", slug_prefix = "{prefix}", period_s = {period} }},')
        out += ["]", ""]
        if "kalshi" not in a.venues:
            out += [
                "# These markets settle on CF Benchmarks' BRTI index (cfbenchmarks:BRTI), which only",
                "# Kalshi's feed streams. For strategies that compare the index with the strike, add",
                "# Kalshi keys to .env and uncomment:",
                "# [feeds.kalshi]",
                '# series = ["KXBTC15M"]',
                '# index_ids = ["BRTI"]',
                "",
            ]
    if not a.venues:
        out += ["[feeds.coinbase]   # public data, no keys", 'products = ["BTC-USD"]', ""]
    return "\n".join(out)


def _experiment(a: Answers) -> str:
    if a.max_qty is not None and a.max_notional is not None:
        qty, notional = f"max_qty = {a.max_qty:g}", f"max_notional = {a.max_notional:g}"
    else:  # commented out: set both to go live
        qty, notional = "# max_qty = 5", "# max_notional = 5"
    caps = f"{qty:<22}# largest single order, contracts\n{notional:<22}# largest single order, $"
